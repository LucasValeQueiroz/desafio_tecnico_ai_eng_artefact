def render(scenario: Scenario, model: str, exchanges: list[dict]) -> str:
    lines = [
        f"# {scenario.title}",
        "",
        f"**What this shows:** {scenario.highlights}",
        "",
        f"Generated by `scripts/generate_examples.py` with `{model}`. Store clock fixed at {scenario.now:%Y-%m-%d %H:%M}. Nothing was edited by hand.",
        "",
        "---",
        "",
    ]
    for exchange in exchanges:
        lines += [f"**Cliente:** {exchange['customer']}", ""]
        if exchange["tools"]:
            calls = "; ".join(f"`{t['tool']}` → {t['status']}" for t in exchange["tools"])
            lines += [f"> _Consultas: {calls}_", ""]
        if exchange["flags"]:
            lines += [f"> _Safety net: {'; '.join(exchange['flags'])}_", ""]
        lines += [f"**Lia:** {exchange['agent']}", ""]
    return "\n".join(lines)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    settings = load_settings()
    llm = build_llm(settings)
    data, policies = StoreData(settings.data_dir), PolicyBook()
    TARGET.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        storage = Storage(Path(tmp) / "examples.db")
        for scenario in SCENARIOS:
            agent = ServiceAgent(data, policies, StoreClock(scenario.now), storage, llm)
            session_id = uuid.uuid4().hex[:12]
            exchanges = []
            for turn in scenario.turns:
                reply = agent.reply(session_id, turn)
                exchanges.append({"customer": turn, "agent": reply.text, "tools": reply.tools_used, "flags": reply.guard_flags})
            path = TARGET / f"{scenario.slug}.md"
            path.write_text(render(scenario, settings.model, exchanges), encoding="utf-8", newline="\n")
            print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
