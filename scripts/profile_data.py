"""Profile the store's records and write docs/data_quality.md.

The agent doesn't correct source records. This report tells the store what to fix, and
each finding says how the agent behaves in the meantime.

    python scripts/profile_data.py
"""
from __future__ import annotations

import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from emporio_agent.pricing import brl  # noqa: E402
from emporio_agent.store_data import StoreData  # noqa: E402

TARGET = ROOT / "docs" / "data_quality.md"


def _table(headers: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines + [""]


def build(data: StoreData) -> str:
    products = data.products.values()
    out = [
        "# Data quality report",
        "",
        "Generated by `scripts/profile_data.py`. Source records are never changed; the agent works around each finding as described.",
        "",
        "## Overview",
        "",
    ]
    counts = collections.Counter(p.category_name for p in products)
    out += _table(
        ["Category", "Products"],
        [[name, counts.get(name, 0)] for name in data.categories.values()],
    )
    empty = [name for name in data.categories.values() if counts.get(name, 0) == 0]
    out += [
        f"{len(data.products)} products, {len(data.customers)} customers, {len(data.orders)} orders, {len(data.promotions)} promotions ({sum(p.active for p in data.promotions)} active).",
        "",
        "## Findings in the records",
        "",
        "### Categories without products",
        "",
        ", ".join(empty) + ".",
        "",
        "**Agent behavior:** says it has no such record instead of inventing a product. The manual's claim of over 300 instruments is treated as outdated.",
        "",
        "### Status and stock disagree",
        "",
    ]
    out += _table(
        ["Product", "Name", "Status", "Stock"],
        [
            [p.id, p.name, p.status, p.stock]
            for p in products
            if (p.status != "active" and p.stock > 0)
        ],
    )
    out += ["**Agent behavior:** status wins, so these aren't offered for purchase even with units in stock.", "", "### Active products without stock", ""]
    out += _table(["Product", "Name"], [[p.id, p.name] for p in products if p.status == "active" and p.stock == 0])
    out += ["**Agent behavior:** reported as temporarily unavailable, with similar alternatives.", "", "### Description contradicts the product name", ""]
    out += _table(
        ["Product", "Name", "Description starts with"],
        [[p.id, p.name, p.description[:60] + "..."] for p in products if p.record_conflict],
    )
    out += [
        "Product 137 also says 5 strings in the description and 4 in the specs, and product 142 says 88 keys against 61.",
        "",
        "**Agent behavior:** the description is withheld from the model, which gives only name, price and availability, and offers to confirm details with the team.",
        "",
        "### Several promotions for one product",
        "",
    ]
    by_product = collections.defaultdict(list)
    for promotion in data.promotions:
        by_product[promotion.product_id].append(promotion)
    out += _table(
        ["Product", "Promotions"],
        [
            [pid, "; ".join(f"{p.description} {p.discount_percent}% ({'active' if p.active else 'inactive'})" for p in promos)]
            for pid, promos in by_product.items()
            if len(promos) > 1
        ],
    )
    out += ["**Agent behavior:** only active promotions apply. All of these are inactive today. If several were active, the largest discount would apply, since discounts don't add up.", "", "### Order total differs from the sum of items at current prices", ""]
    out += _table(
        ["Order", "Status", "Recorded total", "Sum of items"],
        [
            [o.id, o.status, brl(o.total), brl(data.order_total_from_lines(o))]
            for o in data.orders.values()
            if data.order_total_from_lines(o) != o.total
        ],
    )
    out += ["**Agent behavior:** always reports the recorded total. If the customer questions it, the case goes to the team.", "", "### Orders for products not yet launched", ""]
    out += _table(
        ["Order", "Status", "Product"],
        [
            [o.id, o.status, data.products[line.product_id].name]
            for o in data.orders.values()
            for line in o.lines
            if data.products[line.product_id].status == "coming_soon"
        ],
    )
    out += ["**Agent behavior:** reports the order as recorded. The store should review these.", "", "### Customers sharing an email", ""]
    emails = collections.defaultdict(list)
    for customer in data.customers.values():
        emails[customer.email].append(customer.id)
    out += _table(["Email", "Customer ids"], [[e, ids] for e, ids in emails.items() if len(ids) > 1])
    out += [
        "**Agent behavior:** listing orders without an order number requires both email and phone, which separates the two customers. With an order number, the email is checked against that order's owner.",
        "",
        "### Stale order statuses",
        "",
        "The most recent order is from " + max(o.order_date for o in data.orders.values()).strftime("%Y-%m-%d") + ", and some orders remain pending, confirmed or shipped. Against today's date they look abandoned.",
        "",
        "**Agent behavior:** reports the recorded status and flags a shipped order whose estimated delivery has passed. Set `AGENT_NOW` to reproduce a date within the dataset.",
        "",
        "## Contradictions in the manual",
        "",
    ]
    out += _table(
        ["Topic", "Manual says", "Resolution"],
        [
            ["Phone", "(67) 3341-4444 on the cover and section 1.2; (67) 3321-4500 in section 7", "(67) 3341-4444, which appears twice and is labelled as phone and messaging"],
            ["Email", "contato@emporiodamusica.com.br on the cover; contato@empóriodamusica.com.br in section 1.2", "The cover's spelling, since an accented domain looks like a typo"],
            ["Minimum installment", "R$ 100,00 in the section 3 table; R$ 50,00, R$ 80,00 and R$ 100,00 by range in section 3.1", "Section 3.1, because it is more specific"],
            ["Installments up to 3x", "\"no minimum value (except below R$ 50,00)\"", "Read as a R$ 50,00 minimum"],
            ["Partner stores", "Section 7.1 says to suggest them; no store is listed", "No store is named"],
            ["Catalog size", "Over 300 instruments, including wind and orchestral strings", "The records decide what can be sold"],
        ],
    )
    out += [
        "## Gaps in the records",
        "",
        "- **No actual delivery date.** The estimated delivery date stands in for receipt, and replies say so.",
        "- **No purchase channel.** The right of regret applies to online purchases. Orders are treated as online, and the team confirms.",
        "- **No promotion dates.** `is_active` is the only signal of whether a promotion is valid.",
        "- **No final-sale or customization flags.** Section 4.4 exclusions can't be checked automatically, so they are stated as conditions.",
        "- **No partner stores, shipping quotes, or metropolitan-area definition.** Those questions go to the team.",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(build(StoreData(ROOT / "data")), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
